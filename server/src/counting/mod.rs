/// A single-winner Schulze election (`schulze`).
///
/// Same ranked-ballot invariants as [`RankedElection`], plus `seats` must be
/// exactly 1 and a `tie_break_seed` (used for the random lot on beatpath
/// ties). Invariants are enforced at parse time — by
/// [`SchulzeElection::try_new`] and by deserialization (which goes through
/// `try_new` via `try_from`) — so a value of this type is always well-formed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(try_from = "SchulzeElectionRaw")]
pub struct SchulzeElection {
    candidates: Vec<String>,
    seats: usize,
    ballots: Vec<CombinedBallot>,
    tie_break_seed: u64,
}

/// Raw deserialization target for [`SchulzeElection`]; converted through
/// `try_new` so invalid data is rejected at parse time.
#[derive(Debug, Clone, Deserialize)]
struct SchulzeElectionRaw {
    candidates: Vec<String>,
    seats: usize,
    ballots: Vec<CombinedBallot>,
    #[serde(default = "random_tie_break_seed")]
    tie_break_seed: u64,
}

fn random_tie_break_seed() -> u64 {
    rand::random()
}

impl TryFrom<SchulzeElectionRaw> for SchulzeElection {
    type Error = String;

    fn try_from(raw: SchulzeElectionRaw) -> Result<Self, String> {
        Self::try_new(raw.candidates, raw.seats, raw.ballots, raw.tie_break_seed)
    }
}

impl SchulzeElection {
    pub fn try_new(
        candidates: Vec<String>,
        seats: usize,
        ballots: Vec<CombinedBallot>,
        tie_break_seed: u64,
    ) -> Result<Self, String> {
        if candidates.is_empty() {
            return Err("Candidates list cannot be empty".to_string());
        }
        if seats != 1 {
            return Err("Schulze is a single-winner system: seats must be 1".to_string());
        }
        for ballot in &ballots {
            for &rank in &ballot.ranks {
                if let Some(idx) = rank {
                    if idx >= candidates.len() {
                        return Err("Invalid candidate index".to_string());
                    }
                }
            }
        }
        Ok(Self {
            candidates,
            seats,
            ballots,
            tie_break_seed,
        })
    }

    pub fn candidates(&self) -> &[String] {
        &self.candidates
    }
    pub fn seats(&self) -> usize {
        self.seats
    }
    pub fn ballots(&self) -> &[CombinedBallot] {
        &self.ballots
    }
    pub fn tie_break_seed(&self) -> u64 {
        self.tie_break_seed
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(tag = "election_type", rename_all = "kebab-case")]
pub enum Election {
    StvMd(RankedElection),
    StvMdCoperland(RankedElection),
    StvMdGrouped(StvMdGroupedElection),
    Schulze(SchulzeElection),
}

impl Election {
    pub fn candidates(&self) -> &[String] {
        match self {
            Election::StvMd(e) | Election::StvMdCoperland(e) => e.candidates(),
            Election::StvMdGrouped(e) => e.candidates(),
            Election::Schulze(e) => e.candidates(),
        }
    }
    pub fn seats(&self) -> usize {
        match self {
            Election::StvMd(e) | Election::StvMdCoperland(e) => e.seats(),
            Election::StvMdGrouped(e) => e.seats(),
            Election::Schulze(e) => e.seats(),
        }
    }
    pub fn ballots(&self) -> &[CombinedBallot] {
        match self {
            Election::StvMd(e) | Election::StvMdCoperland(e) => e.ballots(),
            Election::StvMdGrouped(e) => e.ballots(),
            Election::Schulze(e) => e.ballots(),
        }
    }
}

